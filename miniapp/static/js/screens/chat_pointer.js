// Указатель рассылки, SOS и находок: заголовок и один абзац.
// Композера, поля ввода и запроса к серверу здесь нет — то же действие остаётся в чате.

export async function render(root, params, ctx) {
  const { h } = ctx;
  const topic = params && params.topic;
  const pages = {
    broadcast: [
      "Рассылка в чате",
      "Откройте в чате раздел «Общение» и кнопку рассылки. Письмо отсюда не отправить.",
    ],
    sos: [
      "SOS в чате",
      "Откройте в чате раздел дня форума и кнопку «SOS». Заявку отсюда не создать.",
    ],
    lost: [
      "Находки в чате",
      "Откройте в чате кнопку находок. Список вещей здесь не ведётся.",
    ],
  };
  const page = pages[topic];
  root.replaceChildren();
  if (!page) {
    root.append(
      h("h1", { text: "В этом режиме пусто" }),
      h("p", { text: "Для вашей роли здесь нет строк. Если дело пропало, попросите того, кто выдаёт доступ, проверить права." }),
    );
    return;
  }
  root.append(
    h("h1", { text: page[0] }),
    h("p", { text: page[1] }),
  );
}
