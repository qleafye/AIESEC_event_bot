def _options(label: str, question: str, defaults: list[str]) -> dict:
    standard = "\n".join(defaults)
    return {
        "type": "list", "group": "reg", "label": label,
        "prompt": (
            f"Варианты-кнопки для вопроса «{question}» — каждый на отдельной строке. "
            f"Стандартный список:\n{standard}\n\nПусто = стандартный список."
        ),
        "default": None,
    }


