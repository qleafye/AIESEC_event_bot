"""Phase 27 (27-03, LANG-04/LANG-10) — глоссарий АЙСЕК: защита терминов и разметки до
машинного перевода, восстановление и пост-замены после.

Латиница здесь ЗАКОННА — этот модуль ИСТОЧНИК английских текстов для делегата (как
`i18n_ui_en.py`), а не текст ДЛЯ РУССКОГО читателя, которого касается правило владельца
«АЙСЕК»/«Юлид» кириллицей. `tests/test_ru_brand_wording_260824.py` этот файл не сканирует
(докстринг сторожа прямо перечисляет исключение).

Ни Argos, ни LibreTranslate, ни NLLB не имеют встроенного глоссария (27-RESEARCH.md, § Glossary
Strategy) — механика здесь СВОЯ, в две стадии:

1. **DNT (do-not-translate)** — термины подставляются ASCII-сентинелами ДО перевода
   (`protect`), после перевода сентинел заменяется на финальный английский эквивалент
   (`restore`). Замер 27-01 (`27-PROBE-REPORT.md`, § «Сентинелы DNT»): 9/9 сентинелов
   пережили перевод дословно во всех позициях (начало/середина/склонение с приклеенным
   русским окончанием) — вердикт «сентинелы переживают перевод», тождественная заглушка
   `protect`/`restore` НЕ нужна.
2. **POST** — регулярные пост-замены частых калек движка на уже переведённом английском
   тексте (утверждённый черновик 27-01, `27-PROBE-REPORT.md`, «Черновик глоссария»).

Обязательные находки замера 27-01 (`27-CONTEXT.md`, «Находки замера, обязательные для
27-03»), реализованные тем же сентинел-механизмом, что и DNT-термины (`protect`/`restore`
работают с ЛЮБОЙ неизменяемой подстрокой — тегом, плейсхолдером или брендом — единообразно):

- HTML-тэги (`<b>`, `</b>`, ...) и `{плейсхолдеры}` ломаются движком (`</b>` → `<// b. >>`,
  найдено на реальном `approve_text` стенда) — заменяются на сентинелы ДО перевода наравне с
  DNT-терминами; если после перевода сентинел тега/плейсхолдера пропал или задвоился —
  `apply()` отбрасывает перевод целиком (возвращает `""` — fail-soft: делегат видит русский,
  см. контракт `translations.text` в `database/db.py`, "failed" = пустая строка).
- Короткие 2-буквенные коды (`TL`→`TLL`, `BD`→`BDB`) — движок их искажает вне зависимости от
  протекции (это не термины из глоссария, а короткие коды `reg_options.*`) — сентинелами не
  лечится, только ручной правкой на экране 27-06 (см. `27-PROBE-REPORT.md`, п.4).
- Ведущий эмодзи/символьный префикс подписи протаскивает кириллический хвост в перевод
  («🎖 Позиция в АЙСЕК» → «ция Position in ISEC») — `split_leading_symbols()` отделяет префикс
  ДО `protect()`/перевода, вызывающий (`services/i18n_worker.py`) приклеивает его обратно
  ПОСЛЕ `apply()`, а не переводит вместе с текстом.

Названия городов — фиксированные соответствия в `DNT` (не MT): замер нашёл MT-артефакты в
нижнем регистре («ekaterinburg», «ufa»), а короткий список из 8 дефолтных городов
(`reg_engine.py::SELECT_CONFIG["city"]`) дешевле и надёжнее задать руками один раз.
"""
from __future__ import annotations

import itertools
import logging
import re

logger = logging.getLogger(__name__)

# ── DNT: подставляются сентинелами ДО перевода, восстанавливаются финальным английским
# эквивалентом ПОСЛЕ (27-01, чекпоинт: «черновик утверждён как есть», расширен городами по
# утверждённому списку 8 дефолтных городов reg_engine.py::SELECT_CONFIG["city"]).
DNT: dict[str, str] = {
    "АЙСЕК": "AIESEC",
    "Юлид": "YouLead",
    "РеалТок": "RealTalk",
    # Города — утверждённый дефолтный список анкеты (reg_engine.py, "city"), фиксированные
    # соответствия вместо MT (27-PROBE-REPORT.md, «Рекомендация» п.4 — MT даёт нижний регистр).
    "Москва и МО": "Moscow and MO",
    "Санкт-Петербург": "St. Petersburg",
    "Новосибирск": "Novosibirsk",
    "Екатеринбург": "Yekaterinburg",
    "Казань": "Kazan",
    "Нижний Новгород": "Nizhny Novgorod",
    "Красноярск": "Krasnoyarsk",
    "Уфа": "Ufa",
    # Quick 260906 (UAT-фикс 27-05): найдено стендовым UAT — движок читал «ФИО» как
    # аббревиатуру-код (тот же класс артефакта, что и `TL`→`TLL`/`BD`→`BDB` в докстринге выше)
    # и отдавал «Fio.» вместо «full name». Длинная форма — до короткой по тому же правилу
    # sorted(key=len, reverse=True) в protect() (не пересекаются подстрокой, но порядок для
    # ясности такой же, как у остальных пар).
    "Фамилия Имя Отчество": "last name, first name, patronymic",
    "ФИО": "full name",
}

# ── POST: чиним ПОСЛЕ перевода частые кальки движка — утверждённый черновик 27-01
# (27-PROBE-REPORT.md, «Черновик глоссария») воспроизведён буквально, без редактуры.
POST: list[tuple[re.Pattern, str]] = [
    (re.compile(r"\bLC\b|\blocal committee\b", re.IGNORECASE), "Local Committee"),
    (re.compile(r"\bИК\b"), "Local Committee"),  # ЛК
    (re.compile(r"\bpersonal message\b", re.IGNORECASE), "direct message"),  # ЛС
]

# HTML-тэги (parse_mode HTML бота — <b>, </b>, <i>, <a href="...">, ...) и «{плейсхолдеры}»
# (format-строки настроек вроде «Продолжить с шага {step} из {total}») — неизменяемые куски,
# которые движок ломает молча (Pitfall замера 27-01). Один шаблон на оба случая — механика
# сентинела одна и та же.
_TAG_OR_PLACEHOLDER_RE = re.compile(r"</?[a-zA-Z][^<>]*>|\{[^{}]+\}")

# Ведущие эмодзи/символы/пробелы перед первой буквой (кириллической или латинской) — `\w` с
# юникодом покрывает буквы любого алфавита, `\W` — всё остальное (эмодзи, пробел, спецсимвол).
_LEADING_SYMBOLS_RE = re.compile(r"^[\W_]+", re.UNICODE)

# ASCII-сентинел ровно в форме, проверенной замером 27-01 («ZQ1Z» и т.п.) — движок копирует
# такие токены дословно (9/9 в замере), не поддаётся склонению/транслитерации.
_SENTINEL_FMT = "ZQ{}Z"


def protect(text: str) -> tuple[str, dict[str, str]]:
    """Заменяет HTML-тэги/плейсхолдеры и DNT-термины на уникальные ASCII-сентинелы ДО
    перевода. Возвращает `(защищённый_текст, mapping)`, где `mapping[сентинел]` — то, чем
    его нужно заменить ПОСЛЕ перевода (`restore`/`apply`): исходная разметка для
    тега/плейсхолдера, финальный английский термин для DNT.

    Каждое вхождение получает СВОЙ сентинел (даже повторный термин в одной строке) — так
    `apply()` может проверить каждый сентинел независимо (`count == 1`), не путая
    «сколько раз термин встретился» с «сколько раз он должен был встретиться»."""
    mapping: dict[str, str] = {}
    counter = itertools.count(1)

    def _wrap(value: str) -> str:
        token = _SENTINEL_FMT.format(next(counter))
        mapping[token] = value
        return token

    protected = _TAG_OR_PLACEHOLDER_RE.sub(lambda m: _wrap(m.group(0)), text)

    # Длинные термины раньше коротких («Нижний Новгород» до отдельного «Новгород», которого
    # тут нет, но принцип общий) — исключает частичное перекрытие при последовательных replace.
    for term in sorted(DNT, key=len, reverse=True):
        target = DNT[term]
        while term in protected:
            protected = protected.replace(term, _wrap(target), 1)

    return protected, mapping


def restore(text: str, mapping: dict[str, str]) -> str:
    """Слепая подстановка: каждый сентинел из `mapping` заменяется на своё финальное
    значение. Проверку «ничего не потерялось» делает `apply()` — `restore()` сама по себе
    ничего не валидирует (нужна отдельно для сценария, где вызывающий уже проверил сентинелы
    сам, например будущий админский предпросмотр на экране 27-06)."""
    for token, value in mapping.items():
        text = text.replace(token, value)
    return text


def apply(text_ru: str, text_en: str, mapping: dict[str, str]) -> str:
    """Восстанавливает сентинелы в `text_en` (результате `driver.translate_batch` на
    защищённом тексте) и прогоняет `POST`-замены. `text_ru` — исходный (защищённый) русский
    текст, используется только для диагностики при отбросе (не участвует в вычислении).

    **Fail-soft по разметке (обязательная находка замера 27-01):** если хоть один сентинел
    из `mapping` пропал или задвоился в `text_en` (движок съел/размножил тег, плейсхолдер
    или DNT-термин) — перевод считается непригодным и отбрасывается: возвращается `""`.
    Это НЕ ошибка драйвера (батч перевёлся, строка в очереди не остаётся) — это ровно
    состояние "failed" из контракта `database/db.py::translations.text` (пустая строка),
    видимое менеджеру на экране 27-06. Вызывающий (`services/i18n_worker.py`) пишет `""` как
    есть — то же самое требование, что и для пустого/совпадающего с исходником перевода."""
    for token in mapping:
        if text_en.count(token) != 1:
            logger.warning(
                "i18n_glossary.apply: перевод отброшен — сентинел %s потерян/задвоен "
                "(ru=%r)", token, text_ru,
            )
            return ""
    restored = restore(text_en, mapping)
    for pattern, repl in POST:
        restored = pattern.sub(repl, restored)
    return restored


def split_leading_symbols(text: str) -> tuple[str, str]:
    """Отделяет ведущие эмодзи/символы/пробелы от текста, начинающегося с буквы (Pitfall
    замера 27-01: «🎖 Позиция в АЙСЕК» → «ция Position in ISEC» — движок иногда съедает кусок
    кириллицы сразу после эмодзи-префикса). Вызывать ДО `protect()`/перевода; префикс
    приклеивается обратно к результату `apply()` как есть, без перевода.

    Возвращает `("", text)`, если префикса нет ИЛИ строка состоит из одних символов (нечего
    отделять содержательно — переводить всё равно нечего)."""
    m = _LEADING_SYMBOLS_RE.match(text)
    if not m or not m.group(0):
        return "", text
    prefix = m.group(0)
    rest = text[len(prefix):]
    if not rest:
        return "", text
    return prefix, rest
