"""Phase 27 (27-03, LANG-04/LANG-10) — глоссарий АЙСЕК: защита терминов и разметки до
машинного перевода, восстановление и пост-замены после.

Латиница здесь ЗАКОННА — этот модуль ИСТОЧНИК английских текстов для делегата (как
`i18n_ui_en.py`), а не текст ДЛЯ РУССКОГО читателя, которого касается правило владельца
«АЙСЕК»/«Юлид» кириллицей. `tests/test_ru_brand_wording_260824.py` этот файл не сканирует
(докстринг сторожа прямо перечисляет исключение).

Ни Argos, ни LibreTranslate, ни NLLB не имеют встроенного глоссария (27-RESEARCH.md, § Glossary
Strategy) — механика здесь СВОЯ, в две стадии:

1. **DNT (do-not-translate)** — термины подставляются ASCII-сентинелами ДО перевода
   (`protect`), после перевода сентинел заменяется на финальный английский эквивалент
   (`restore`). Замер 27-01 (`27-PROBE-REPORT.md`, § «Сентинелы DNT»): 9/9 сентинелов
   пережили перевод дословно во всех позициях (начало/середина/склонение с приклеенным
   русским окончанием) — вердикт «сентинелы переживают перевод», тождественная заглушка
   `protect`/`restore` НЕ нужна.
2. **POST** — регулярные пост-замены частых калек движка на уже переведённом английском
   тексте (утверждённый черновик 27-01, `27-PROBE-REPORT.md`, «Черновик глоссария»).

Обязательные находки замера 27-01 (`27-CONTEXT.md`, «Находки замера, обязательные для
27-03»), реализованные тем же сентинел-механизмом, что и DNT-термины (`protect`/`restore`
работают с ЛЮБОЙ неизменяемой подстрокой — тегом, плейсхолдером или брендом — единообразно):

- HTML-тэги (`<b>`, `</b>`, ...) и `{плейсхолдеры}` ломаются движком (`</b>` → `<// b. >>`,
  найдено на реальном `approve_text` стенда) — заменяются на сентинелы ДО перевода наравне с
  DNT-терминами; если после перевода сентинел тега/плейсхолдера пропал или задвоился —
  `apply()` отбрасывает перевод целиком (возвращает `""` — fail-soft: делегат видит русский,
  см. контракт `translations.text` в `database/db.py`, "failed" = пустая строка).
- Короткие 2-буквенные коды (`TL`→`TLL`, `BD`→`BDB`) — движок их искажает вне зависимости от
  протекции (это не термины из глоссария, а короткие коды `reg_options.*`) — сентинелами не
  лечится, только ручной правкой на экране 27-06 (см. `27-PROBE-REPORT.md`, п.4).
- Ведущий эмодзи/символьный префикс подписи протаскивает кириллический хвост в перевод
  («🎖 Позиция в АЙСЕК» → «ция Position in ISEC») — `split_leading_symbols()` отделяет префикс
  ДО `protect()`/перевода, вызывающий (`services/i18n_worker.py`) приклеивает его обратно
  ПОСЛЕ `apply()`, а не переводит вместе с текстом.

Названия городов — фиксированные соответствия в `DNT` (не MT): замер нашёл MT-артефакты в
нижнем регистре («ekaterinburg», «ufa»), а короткий список из 8 дефолтных городов
(`reg_engine.py::SELECT_CONFIG["city"]`) дешевле и надёжнее задать руками один раз.

**UAT 260906 (стендовый прогон 3, найдено ПОСЛЕ 27-01): пробел в методике замера.** Все 9/9
кейсов замера («Сентинелы DNT» выше) подставляли сентинел ВНУТРИ реального русского
предложения («ZQ1Z проводит форум...»). Ни один не проверял сентинел как ЕДИНСТВЕННОЕ
содержимое строки — а ровно так выглядит любой DNT-город в списке опций анкеты: вся строка
«Москва и МО» после `protect()` превращается в один голый сентинел без единого реального
слова вокруг. На этом изолированном случае движок ведёт себя иначе: «Москва и МО» →
«Moscow and MOZ», «Казань» → «KazanZ» — финальный символ суффикса сентинела («Z»)
дублируется/утаскивается движком за пределы токена (скорее всего постобработка
детокенизации/truecasing у argos-translate-lt видит однобуквенный суффикс, совпадающий с
первой буквой префикса, как обрывок регистровой разметки, и не полностью его поглощает).
Старый `apply()` проверял точное вхождение сентинела строкой (`text.count(token) == 1`) —
проверка проходила (сам токен цел), но лишний символ ПОСЛЕ токена оставался в тексте как
есть. Фикс двух частей:

1. Суффикс сентинела расширен с одного символа до двух («QZ» вместо «Z») — убирает саму
   форму «однобуквенный хвост = первая буква префикса», которая похожа на артефакт
   регистровой разметки.
2. `restore`/`apply` ищут сентинел терпимым регэкспом (`_tolerant_sentinel_re`), а не точной
   строкой: регистронезависимость, необязательные пробелы между буквами маркера (движок
   иногда токенизирует посимвольно), один посторонний маркерный символ вплотную ДО/ПОСЛЕ
   токена поглощается вместе с ним (не остаётся в тексте), один точечный символ вплотную
   ПОСЛЕ токена тоже поглощается (тот же класс артефакта, что дал «Fio.» вместо «ФИО» до
   DNT-фикса — движок иногда трактует одинокий ASCII-токен как аббревиатуру и приклеивает
   точку). Если сентинела целиком нет ИЛИ он задвоен — `apply()` по-прежнему отбрасывает
   перевод (fail-soft, `""`), терпимость касается только косметического дрейфа вокруг УЖЕ
   найденного токена, не факта его присутствия.
"""
from __future__ import annotations

import itertools
import logging
import re

logger = logging.getLogger(__name__)

# ── DNT: подставляются сентинелами ДО перевода, восстанавливаются финальным английским
# эквивалентом ПОСЛЕ (27-01, чекпоинт: «черновик утверждён как есть», расширен городами по
# утверждённому списку 8 дефолтных городов reg_engine.py::SELECT_CONFIG["city"]).
DNT: dict[str, str] = {
    "АЙСЕК": "AIESEC",
    "Юлид": "YouLead",
    "РеалТок": "RealTalk",
    # Города — утверждённый дефолтный список анкеты (reg_engine.py, "city"), фиксированные
    # соответствия вместо MT (27-PROBE-REPORT.md, «Рекомендация» п.4 — MT даёт нижний регистр).
    "Москва и МО": "Moscow and MO",
    "Санкт-Петербург": "St. Petersburg",
    "Новосибирск": "Novosibirsk",
    "Екатеринбург": "Yekaterinburg",
    "Казань": "Kazan",
    "Нижний Новгород": "Nizhny Novgorod",
    "Красноярск": "Krasnoyarsk",
    "Уфа": "Ufa",
    # Quick 260906 (UAT-фикс 27-05): найдено стендовым UAT — движок читал «ФИО» как
    # аббревиатуру-код (тот же класс артефакта, что и `TL`→`TLL`/`BD`→`BDB` в докстринге выше)
    # и отдавал «Fio.» вместо «full name». Длинная форма — до короткой по тому же правилу
    # sorted(key=len, reverse=True) в protect() (не пересекаются подстрокой, но порядок для
    # ясности такой же, как у остальных пар).
    "Фамилия Имя Отчество": "last name, first name, patronymic",
    "ФИО": "full name",
}

# ── POST: чиним ПОСЛЕ перевода частые кальки движка — утверждённый черновик 27-01
# (27-PROBE-REPORT.md, «Черновик глоссария») воспроизведён буквально, без редактуры.
POST: list[tuple[re.Pattern, str]] = [
    (re.compile(r"\bLC\b|\blocal committee\b", re.IGNORECASE), "Local Committee"),
    (re.compile(r"\bИК\b"), "Local Committee"),  # ЛК
    (re.compile(r"\bpersonal message\b", re.IGNORECASE), "direct message"),  # ЛС
]

# HTML-тэги (parse_mode HTML бота — <b>, </b>, <i>, <a href="...">, ...) и «{плейсхолдеры}»
# (format-строки настроек вроде «Продолжить с шага {step} из {total}») — неизменяемые куски,
# которые движок ломает молча (Pitfall замера 27-01). Один шаблон на оба случая — механика
# сентинела одна и та же.
_TAG_OR_PLACEHOLDER_RE = re.compile(r"</?[a-zA-Z][^<>]*>|\{[^{}]+\}")

# Ведущие эмодзи/символы/пробелы перед первой буквой (кириллической или латинской) — `\w` с
# юникодом покрывает буквы любого алфавита, `\W` — всё остальное (эмодзи, пробел, спецсимвол).
_LEADING_SYMBOLS_RE = re.compile(r"^[\W_]+", re.UNICODE)

# Симметрично ведущим — замыкающие эмодзи/символы/пробелы ПОСЛЕ последней буквы (UAT 260906:
# «...в меню ниже 👇» → «...below e», движок съедает замыкающий эмодзи и оставляет постороннюю
# букву на его месте — тот же класс Pitfall'а, что и ведущий эмодзи-префикс, с другого конца
# строки, см. `split_trailing_symbols`).
_TRAILING_SYMBOLS_RE = re.compile(r"[\W_]+$", re.UNICODE)

# Русская скобочная гендерная приписка («зарегистрирован(а)», «был(а)», «Сам(а)») — слитно с
# предыдущей буквой, без пробела (ровно так во всём делегатском корпусе). У английского нет
# грамматического рода — приписка при переводе не нужна и даёт «(a)» латиницей в переводе (UAT
# 260906), см. `strip_gender_suffix`.
_GENDER_SUFFIX_RE = re.compile(r"(?<=[а-яёА-ЯЁ])\((?:а|ла)\)")

# ASCII-сентинел, форма замера 27-01 расширена по находке UAT 260906 (докстринг модуля,
# «пробел в методике замера»): суффикс — ДВА символа («QZ»), не один («Z» как раньше) — не
# похож на однобуквенный хвост регистровой разметки, который движок утаскивал за пределы
# токена на изолированных (без окружающего текста) сентинелах.
_SENTINEL_PREFIX = "ZQ"
_SENTINEL_SUFFIX = "QZ"
_SENTINEL_FMT = _SENTINEL_PREFIX + "{}" + _SENTINEL_SUFFIX

# Только эти буквы участвуют в маркере сентинела — их же алфавит используется ниже как
# «посторонний маркерный символ», который терпимый регэксп поглощает вплотную к токену.
_SENTINEL_MARKER_CHARS = "".join(sorted(set(_SENTINEL_PREFIX + _SENTINEL_SUFFIX)))

_SENTINEL_TOKEN_RE = re.compile(
    r"^" + re.escape(_SENTINEL_PREFIX) + r"(\d+)" + re.escape(_SENTINEL_SUFFIX) + r"$"
)


def _tolerant_sentinel_re(token: str) -> re.Pattern[str]:
    """Терпимый паттерн под ОДИН конкретный сентинел-токен (`"ZQ3QZ"` и т.п., выданный
    `protect()`). Ловит сам токен ТОЧНО (число сентинела — literal, не `\\d+`, чужой сентинел
    не подхватит), но терпим к косметическому дрейфу движка вокруг него (UAT 260906,
    докстринг модуля):

    - регистр (движок иногда отдаёт `zq3qz`) — весь паттерн `re.IGNORECASE`;
    - пробел между буквами маркера (посимвольная токенизация) — `\\s*` между КАЖДОЙ буквой
      префикса/суффикса и перед/после числа;
    - один посторонний символ из алфавита маркера (`Q`/`Z`) вплотную ДО или ПОСЛЕ токена —
      поглощается вместе с ним, а не остаётся ошмётком рядом с восстановленным термином (это
      и есть находка UAT — «MOZ» вместо «MO» после восстановления);
    - одна точка вплотную ПОСЛЕ токена — поглощается тем же приёмом (класс артефакта
      «Fio.» вместо «ФИО», движок иногда завершает одинокий ASCII-токен точкой, как
      аббревиатуру).

    Отсутствие/задвоение токена регэксп НЕ лечит — это по-прежнему решает `apply()` подсчётом
    числа совпадений (fail-soft `""`), терпимость только вокруг УЖЕ найденного токена."""
    match = _SENTINEL_TOKEN_RE.match(token)
    if not match:
        raise ValueError(f"i18n_glossary: не сентинел вида {_SENTINEL_FMT!r}: {token!r}")
    number = match.group(1)
    prefix_core = r"\s*".join(re.escape(ch) for ch in _SENTINEL_PREFIX)
    suffix_core = r"\s*".join(re.escape(ch) for ch in _SENTINEL_SUFFIX)
    stray = f"[{re.escape(_SENTINEL_MARKER_CHARS)}]?"
    pattern = (
        f"{stray}{prefix_core}\\s*{re.escape(number)}\\s*{suffix_core}{stray}\\.?"
    )
    return re.compile(pattern, re.IGNORECASE)


def protect(text: str) -> tuple[str, dict[str, str]]:
    """Заменяет HTML-тэги/плейсхолдеры и DNT-термины на уникальные ASCII-сентинелы ДО
    перевода. Возвращает `(защищённый_текст, mapping)`, где `mapping[сентинел]` — то, чем
    его нужно заменить ПОСЛЕ перевода (`restore`/`apply`): исходная разметка для
    тега/плейсхолдера, финальный английский термин для DNT.

    Каждое вхождение получает СВОЙ сентинел (даже повторный термин в одной строке) — так
    `apply()` может проверить каждый сентинел независимо (`count == 1`), не путая
    «сколько раз термин встретился» с «сколько раз он должен был встретиться»."""
    mapping: dict[str, str] = {}
    counter = itertools.count(1)

    def _wrap(value: str) -> str:
        token = _SENTINEL_FMT.format(next(counter))
        mapping[token] = value
        return token

    protected = _TAG_OR_PLACEHOLDER_RE.sub(lambda m: _wrap(m.group(0)), text)

    # Длинные термины раньше коротких («Нижний Новгород» до отдельного «Новгород», которого
    # тут нет, но принцип общий) — исключает частичное перекрытие при последовательных replace.
    for term in sorted(DNT, key=len, reverse=True):
        target = DNT[term]
        while term in protected:
            protected = protected.replace(term, _wrap(target), 1)

    return protected, mapping


def restore(text: str, mapping: dict[str, str]) -> str:
    """Слепая подстановка: каждый сентинел из `mapping` заменяется на своё финальное
    значение терпимым регэкспом (`_tolerant_sentinel_re` — переживает косметический дрейф
    движка вокруг токена, UAT 260906). Проверку «ничего не потерялось» делает `apply()` —
    `restore()` сама по себе ничего не валидирует (нужна отдельно для сценария, где
    вызывающий уже проверил сентинелы сам, например будущий админский предпросмотр на экране
    27-06)."""
    for token, value in mapping.items():
        text = _tolerant_sentinel_re(token).sub(lambda _m, v=value: v, text)
    return text


def apply(text_ru: str, text_en: str, mapping: dict[str, str]) -> str:
    """Восстанавливает сентинелы в `text_en` (результате `driver.translate_batch` на
    защищённом тексте) и прогоняет `POST`-замены. `text_ru` — исходный (защищённый) русский
    текст, используется только для диагностики при отбросе (не участвует в вычислении).

    Поиск сентинела — терпимый регэксп (`_tolerant_sentinel_re`), не точная строка: движок
    иногда меняет регистр/пробелы или оставляет один посторонний маркерный символ вплотную к
    токену (UAT 260906, докстринг модуля) — это косметика, не потеря. `apply()` восстанавливает
    ТОЧНЫЙ финальный термин без огрызков маркера рядом с ним.

    **Fail-soft по разметке (обязательная находка замера 27-01):** если хоть один сентинел
    из `mapping` пропал или задвоился в `text_en` (движок съел/размножил тег, плейсхолдер
    или DNT-термин) — перевод считается непригодным и отбрасывается: возвращается `""`.
    Это НЕ ошибка драйвера (батч перевёлся, строка в очереди не остаётся) — это ровно
    состояние "failed" из контракта `database/db.py::translations.text` (пустая строка),
    видимое менеджеру на экране 27-06. Вызывающий (`services/i18n_worker.py`) пишет `""` как
    есть — то же самое требование, что и для пустого/совпадающего с исходником перевода."""
    working = text_en
    for token, value in mapping.items():
        pattern = _tolerant_sentinel_re(token)
        matches = pattern.findall(working)
        if len(matches) != 1:
            logger.warning(
                "i18n_glossary.apply: перевод отброшен — сентинел %s потерян/задвоен "
                "(ru=%r, en=%r)", token, text_ru, text_en,
            )
            return ""
        working = pattern.sub(lambda _m, v=value: v, working, count=1)
    for pattern, repl in POST:
        working = pattern.sub(repl, working)
    return working


def split_leading_symbols(text: str) -> tuple[str, str]:
    """Отделяет ведущие эмодзи/символы/пробелы от текста, начинающегося с буквы (Pitfall
    замера 27-01: «🎖 Позиция в АЙСЕК» → «ция Position in ISEC» — движок иногда съедает кусок
    кириллицы сразу после эмодзи-префикса). Вызывать ДО `protect()`/перевода; префикс
    приклеивается обратно к результату `apply()` как есть, без перевода.

    Возвращает `("", text)`, если префикса нет ИЛИ строка состоит из одних символов (нечего
    отделять содержательно — переводить всё равно нечего)."""
    m = _LEADING_SYMBOLS_RE.match(text)
    if not m or not m.group(0):
        return "", text
    prefix = m.group(0)
    rest = text[len(prefix):]
    if not rest:
        return "", text
    return prefix, rest


def split_trailing_symbols(text: str) -> tuple[str, str]:
    """Отделяет замыкающие эмодзи/символы/пробелы от текста, оканчивающегося буквой — тот же
    Pitfall, что и `split_leading_symbols` (докстринг выше), с другого конца строки (UAT
    260906: «С возвращением! ...в меню ниже 👇» → «...below e» — движок съедает замыкающий
    эмодзи и оставляет постороннюю букву на его месте, эмодзи нетронутым он не переживает,
    в отличие от ASCII-сентинелов). Вызывать ПОСЛЕ `split_leading_symbols()` (на остатке) и
    ДО `protect()`/перевода; суффикс приклеивается обратно к результату `apply()` как есть,
    без перевода — символично то же решение, что уже работает для ведущего префикса.

    Возвращает `(text, "")`, если суффикса нет ИЛИ строка состоит из одних символов (нечего
    отделять содержательно — переводить всё равно нечего)."""
    m = _TRAILING_SYMBOLS_RE.search(text)
    if not m or not m.group(0):
        return text, ""
    suffix = m.group(0)
    rest = text[: -len(suffix)]
    if not rest:
        return text, ""
    return rest, suffix


def strip_gender_suffix(text: str) -> str:
    """Убирает русскую скобочную гендерную приписку («зарегистрирован(а)» → «зарегистрирован»,
    «был(а)» → «был», «Сам(а)» → «Сам») ДО перевода (UAT 260906: движок отдавал приписку как
    есть, «...registered (a) — everything...» — у английского нет грамматического рода,
    латинское «(a)» в переводе не сообщает делегату ничего). Оставшееся слово — мужской род по
    умолчанию — переводится обычным образом, без сентинела: это не термин глоссария, а чистка
    исходного текста перед движком."""
    return _GENDER_SUFFIX_RE.sub("", text)
