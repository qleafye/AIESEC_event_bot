"""Quick 260904-3vm (решение владельца 04.09: «эстафета» вместо двустороннего синхрона фазы 21).

Правила владения черновиком `reg_drafts` — ЧИСТЫЕ функции, без aiogram и без FastAPI, чтобы
их мог импортировать и процесс бота (`handlers/reg_handoff.py`), и веб-процесс
(`miniapp/routers/form.py`) без циклов и без тяжёлых зависимостей на другой стороне.

Модель: анкета в каждый момент открыта РОВНО в одном месте — в чате бота ИЛИ в приложении.
`reg_drafts.active_surface` хранит, у кого сейчас владение:

- `SURFACE_BOT` ("bot") — держит бот; ответы в чат пишутся как обычно, приложение получает
  409 на попытку записи.
- `SURFACE_APP` ("app") — держит приложение; бот НЕ трактует текст делегата как ответ на
  вопрос анкеты (см. `handlers/reg_handoff.py::RegHandoffGuard`), а предлагает кнопку возврата.
- `None` (ничей) — черновик либо пустой (ответов ещё нет — терять нечего, поэтому занимается
  МОЛЧА, без экрана-подтверждения делегату), либо уже отправляется (`submitting_at` заполнен —
  анкета в процессе финализации, владеть уже нечем, обе поверхности должны отступить).

NULL у строк, заведённых ДО этой фичи (Phase 21 и раньше), трактуется как владение бота — их
всегда заводил бот, отдельного backfill колонки не делаем (см. миграцию в `database/db.py`).
"""
from __future__ import annotations

SURFACE_BOT = "bot"
SURFACE_APP = "app"


def draft_holder(draft: dict | None) -> str | None:
    """Кто сейчас владеет черновиком — `SURFACE_BOT` / `SURFACE_APP` / `None` (ничей)."""
    if not draft:
        return None
    if draft.get("submitting_at"):
        # Анкета уже уходит в финализацию — ни одна поверхность больше не владеет ею
        # (обе должны увидеть "ничей" и отступить, а не продолжать писать в черновик,
        # который вот-вот удалится).
        return None
    surface = draft.get("active_surface")
    if surface in (SURFACE_BOT, SURFACE_APP):
        return surface
    # surface is None: либо старая строка (Phase 21 и раньше — трактуем как "bot"), либо
    # черновик реально пуст (ответов нет — занимать нечего, отдаём его молча тому, кто
    # попросит первым, без экрана-подтверждения делегату).
    if draft.get("answers"):
        return SURFACE_BOT
    return None


__all__ = ["SURFACE_BOT", "SURFACE_APP", "draft_holder"]
